import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..')
const artifactPath = resolve(
  root,
  'contracts/out/DirectionalTaxHookFactory.sol/DirectionalTaxHookFactory.json',
)
const outputPath = resolve(root, 'src/generated/directionalTaxFactoryBytecode.ts')
const artifact = JSON.parse(readFileSync(artifactPath, 'utf8'))
const bytecode = artifact?.bytecode?.object

if (typeof bytecode !== 'string' || !bytecode.startsWith('0x') || bytecode.length < 100) {
  throw new Error(`Invalid factory bytecode in ${artifactPath}`)
}
if (Object.keys(artifact?.bytecode?.linkReferences ?? {}).length > 0) {
  throw new Error('Factory bytecode contains unresolved library links')
}

const source = `// Generated by scripts/export-directional-tax-artifact.mjs. Do not edit by hand.\n` +
  `export const DIRECTIONAL_TAX_FACTORY_BYTECODE = '${bytecode}' as const\n`
writeFileSync(outputPath, source, 'utf8')
console.log(`Wrote ${outputPath} (${(bytecode.length - 2) / 2} bytes)`)
