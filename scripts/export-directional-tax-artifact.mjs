import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..')
const outputs = [
  {
    artifact: 'contracts/out/DirectionalTaxHookFactory.sol/DirectionalTaxHookFactory.json',
    output: 'src/generated/directionalTaxFactoryBytecode.ts',
    constant: 'DIRECTIONAL_TAX_FACTORY_BYTECODE',
  },
  {
    artifact: 'contracts/out/ConfigurableTaxHookFactoryV2.sol/ConfigurableTaxHookFactoryV2.json',
    output: 'src/generated/configurableTaxFactoryV2Bytecode.ts',
    constant: 'CONFIGURABLE_TAX_FACTORY_V2_BYTECODE',
  },
]

for (const item of outputs) {
  const artifactPath = resolve(root, item.artifact)
  const outputPath = resolve(root, item.output)
  const artifact = JSON.parse(readFileSync(artifactPath, 'utf8'))
  const bytecode = artifact?.bytecode?.object

  if (typeof bytecode !== 'string' || !bytecode.startsWith('0x') || bytecode.length < 100) {
    throw new Error(`Invalid factory bytecode in ${artifactPath}`)
  }
  if (Object.keys(artifact?.bytecode?.linkReferences ?? {}).length > 0) {
    throw new Error(`Factory bytecode contains unresolved library links: ${artifactPath}`)
  }

  const source = `// Generated by scripts/export-directional-tax-artifact.mjs. Do not edit by hand.\n` +
    `export const ${item.constant} = '${bytecode}' as const\n`
  writeFileSync(outputPath, source, 'utf8')
  console.log(`Wrote ${outputPath} (${(bytecode.length - 2) / 2} bytes)`)
}
